/* ---------- פענוח הכתיב המקוצר ---------- */
function parseMel(str){
  return String(str).trim().split(/\s+/).filter(Boolean).map(tok => {
    const [n, d] = tok.split("/");
    const len = d === undefined ? 1 : parseFloat(d);
    return [n === "r" ? null : normNote(n), len];
  });
}

const SONGS = SONG_SRC.map(s => ({
  id: s.id, title: s.he, intl: s.t, pd: s.pd, who: s.who, year: s.year, url: s.url,
  level: s.lvl, bpm: s.bpm, style: s.sty,
  chords: s.ch || "", notes: parseMel(s.n),
  instruments: instFor(s)
}));

/* איזה כלי מתאים לשיר – לפי מנעד אמיתי, לא "הכול לכולם" */
function instFor(s){
  const notes = parseMel(s.n).map(x => x[0]).filter(Boolean);
  const out = ["piano"];
  if(!notes.length) return out;
  const midi = notes.map(n => {
    const m = /^([A-G]#?)(-?\d)$/.exec(normNote(n));
    return NOTE_ORDER.indexOf(m[1]) + (parseInt(m[2], 10) + 1) * 12;
  });
  const lo = Math.min(...midi), hi = Math.max(...midi), span = hi - lo;

  /* חלילית סופרן: מ-C5 ומעלה, ולא יותר משתי אוקטבות */
  if(lo >= 60 && hi <= 89 && span <= 24) out.push("recorder");
  /* גיטרה ואוקולילה: צריך אקורדים; אוקולילה בטווח צר יותר */
  if(s.ch){
    out.push("guitar");
    if(lo >= 60 && hi <= 84) out.push("ukulele");
  }
  /* בס: מנגינה נמוכה, או שאפשר להוריד אותה אוקטבה בנוחות */
  if(lo <= 64) out.push("bass");
  /* תופים: שיר עם דופק אחיד – ערכי אורך מעטים וללא שברים מסובכים */
  const durs = new Set(parseMel(s.n).map(x => x[1]));
  if(durs.size <= 3 && s.lvl <= 3) out.push("drums");
  return out;
}

const SONG_BY_ID = Object.fromEntries(SONGS.map(s => [s.id, s]));
